export const AEGIS_SUBAGENTS: readonly AegisSubagentSpec[] = AEGIS_DIRECTORS.flatMap(director => {
  const entries = SUBAGENT_NAMES_BY_DEPT[director.departmentId] ?? [];
  return entries.map(([rawName, role], index) => {
    const cleanName = rawName.trim();
    return {
      id: `aegis-sub-d${String(director.departmentId).padStart(2, '0')}-n${index + 1}`,
      directorId: director.id,
      departmentId: director.departmentId,
      nodeNumber: index + 1,
      name: cleanName,
      role,
      skills: [...director.skills],
      tools: [...director.tools],
      scope: `${director.domain}: ${role}`,
    };
  });
});
